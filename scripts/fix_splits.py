"""Build configs/split_fixes.yaml from results/dataset/duplicates.csv.

Usage:  python scripts/check_dataset.py   # finds near-duplicates
        python scripts/fix_splits.py      # writes configs/split_fixes.yaml and applies it
        python scripts/check_dataset.py   # re-check: cross-split pairs must be 0

Method (deterministic, no randomness -> no seed needed):
  1. Near-duplicate pairs = perceptual-hash (pHash) Hamming distance <= 6.
  2. Pairs are merged into groups with union-find (A~B and B~C -> {A,B,C}).
  3. A group that spans several splits is moved entirely into ONE split, chosen by
     priority train > val > test. So val/test only lose images whose copy is in train,
     and no image in val/test has a (near-)copy in another split.
"""
from __future__ import annotations

import csv

import yaml

from common import RESULTS_DIR, ROOT
from prepare_data import SPLIT_FIXES_FILE, apply_split_fixes

PRIORITY = {"train": 0, "val": 1, "test": 2}


def main() -> None:
    rows = list(csv.DictReader(open(RESULTS_DIR / "dataset" / "duplicates.csv")))
    parent: dict[tuple, tuple] = {}

    def find(x):
        parent.setdefault(x, x)
        while parent[x] != x:
            parent[x] = parent[parent[x]]
            x = parent[x]
        return x

    for r in rows:
        a, b = (r["split_a"], r["file_a"]), (r["split_b"], r["file_b"])
        parent[find(a)] = find(b)

    groups: dict[tuple, list] = {}
    for node in list(parent):
        groups.setdefault(find(node), []).append(node)

    moves = []
    for members in groups.values():
        splits = {s for s, _ in members}
        if len(splits) == 1:
            continue
        target = min(splits, key=PRIORITY.get)
        for s, f in sorted(members):
            if s != target:
                moves.append({"file": f, "from": s, "to": target})

    # Keep previously recorded moves (the csv is regenerated after fixing and then has no cross-split pairs)
    old = []
    if SPLIT_FIXES_FILE.exists():
        old = (yaml.safe_load(SPLIT_FIXES_FILE.read_text()) or {}).get("moves", [])
    known = {(m["file"], m["from"]) for m in old}
    all_moves = old + [m for m in moves if (m["file"], m["from"]) not in known]

    SPLIT_FIXES_FILE.parent.mkdir(parents=True, exist_ok=True)
    header = ("# Generated by scripts/fix_splits.py - moves near-duplicate images so that every\n"
              "# duplicate group lives in a single split (priority train > val > test).\n")
    SPLIT_FIXES_FILE.write_text(header + yaml.safe_dump({"moves": all_moves}, sort_keys=False))
    print(f"{len(all_moves)} move(s) recorded in {SPLIT_FIXES_FILE.relative_to(ROOT)}")
    print(f"Applied now: {apply_split_fixes()} image(s) moved")


if __name__ == "__main__":
    main()
